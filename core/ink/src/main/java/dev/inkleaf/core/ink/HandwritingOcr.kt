package dev.inkleaf.core.ink

import android.graphics.Bitmap

/**
 * 一次识别的结果。
 *
 * [confidence] 刻意可空：有的引擎根本算不出置信度，让它填一个"看起来像"
 * 的数字，等于把猜测包装成事实 —— 而"这条笔记是不是这一句"是要用户自己判断的，
 * 界面不该替他把不确定性抹掉。没有就是 null，界面也就不显示。
 */
data class OcrResult(
    val text: String,
    /** 0..1，越大越可信。算不出来就是 null。 */
    val confidence: Float? = null,
)

/**
 * 手写识别引擎的插拔口（S3 的 L3）。
 *
 * ## 为什么不内置模型
 *
 * 中文手写模型有三笔成本，没有一笔是本应用该付的：
 *
 * 1. **体积**：十几到几十 MB。本应用到今天没有申请任何权限、也没有下载过任何东西，
 *    为一个"也许会用到"的功能把安装包撑大几倍，是把成本转嫁给全部用户。
 * 2. **准确率**：手写体（尤其是连笔与草书）的识别率至今不稳。认错了还显示得很自信，
 *    比不认更糟 —— 用户会以为书里真的写了那句话。
 * 3. **隐私叙事**：本应用现在可以说"你的字从未离开这台设备"。一旦内置模型，
 *    这句话要么要重写，要么要额外解释模型在哪跑。
 *
 * 所以这里只留接口：**模型不内置**。
 *
 * ## 怎么接
 *
 * 实现本接口，在 `AppContainer` 构造的地方赋给 `handwritingOcr`（默认是 null）。
 * 界面在它为 null 时不显示任何识别入口 —— 没有一个"点了没反应"的按钮，
 * 也没有一处假装能识别的地方。
 *
 * ## 输入是什么
 *
 * 传进来的是 [InkThumbnail] 渲染出的那张小图（只有这条笔记自己的墨，没有正文）。
 * 不给整页：整页图里绝大部分是印刷体，手写引擎在印刷体上给出的结果没有意义，
 * 而且"这一页里我写了什么"这个问题的答案本来就该由"哪些墨是我写的"决定。
 */
interface HandwritingOcr {

    /** 引擎身份。会显示在界面上，让用户知道这一段字是谁认的。 */
    val id: String

    /** 界面上显示的名字。 */
    val displayName: String

    /**
     * 认一张图里的手写。
     *
     * 允许抛异常：调用方已经用 `runCatching` 兜住，失败会如实告诉用户
     * （"识别失败"而不是"没认出来"—— 两者对用户意味着完全不同的下一步）。
     *
     * @return 认出的文字；`null` 表示"认不出来"（不是失败）。
     *         返回空串与返回 null 是同一件事，调用方都按"没认出来"处理。
     */
    suspend fun recognize(bitmap: Bitmap): OcrResult?
}
